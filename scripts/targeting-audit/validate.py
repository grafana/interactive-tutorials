#!/usr/bin/env python3
"""Validate all packages with CI's pinned CLI and compare two generated trees.
Usage: python3 scripts/targeting-audit/validate.py /path/to/grafana-pathfinder-app
Outputs stay outside the working tree, matching CI's generated-artifact policy.
"""
import hashlib,io,json,pathlib,shutil,subprocess,sys,tarfile,tempfile
root=pathlib.Path(__file__).resolve().parents[2];checkout=pathlib.Path(sys.argv[1]).resolve()
pin='8262a2562c41c8a0a626a6f9e7d7f2405e4a31db'
def run(args,cwd,log):
 result=subprocess.run(args,cwd=cwd,stdout=log,stderr=subprocess.STDOUT)
 return result.returncode==0
with tempfile.TemporaryDirectory(prefix='tutorial-targeting-validation-') as tmp:
 temp=pathlib.Path(tmp);cli=temp/'cli';cli.mkdir()
 archive=subprocess.check_output(['git','archive',pin],cwd=checkout)
 with tarfile.open(fileobj=io.BytesIO(archive)) as tar:tar.extractall(cli,filter='data')
 (cli/'node_modules').symlink_to((checkout/'node_modules').resolve())
 logpath=pathlib.Path('/tmp/tutorial-targeting-validation.log')
 with logpath.open('w') as log:
  assert run(['npm','run','build:cli'],cli,log),str(logpath)
  command=['node',str(cli/'dist/cli/cli/index.js')]
  files=subprocess.check_output(['git','ls-files'],cwd=root).decode().splitlines()
  trees=[]
  for name in ['first','second']:
   tree=temp/name;tree.mkdir();trees.append(tree)
   for f in files:
    src=root/f
    if src.is_file() and not f.startswith('.git'):
     dest=tree/f;dest.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(src,dest)
  tree=trees[0]
  assert run(command+['build-snippets','shared/snippets','-o','/tmp/tutorial-targeting-snippets.json'],tree,log)
  failures=[];contents=sorted(tree.rglob('content.json'));manifests=sorted(tree.rglob('manifest.json'))
  # Validation only reads the staged trees; bounded parallelism avoids 1,451
  # serial Node startups. Every result is collected before generation begins.
  from concurrent.futures import ThreadPoolExecutor
  jobs=[(file, command+['validate','--strict','--snippets-catalog','/tmp/tutorial-targeting-snippets.json',str(file)]) for file in contents]
  jobs += [(file, command+['validate','--package',str(file.parent),'--snippets-catalog','/tmp/tutorial-targeting-snippets.json']) for file in manifests]
  def validate(job):
   file,args=job
   return None if run(args,tree,log) else str(file.relative_to(tree))
  with ThreadPoolExecutor(max_workers=4) as pool:
   failures=[failure for failure in pool.map(validate,jobs) if failure]
  generated=[]
  for tree in trees:
   for args in [['build-stats','.','--exclude','shared'],['build-repository','.','--exclude','shared','-o','repository.json'],['build-graph','interactive-tutorials:repository.json','-o','graph.json']]:
    assert run(command+args,tree,log),(args,str(logpath))
   # Schema is generated by the pinned CLI, never hand-edited.
   schema=subprocess.check_output(command+['schema','manifest'],cwd=tree)
   # Generation timestamps are metadata, not content; normalize only those keys.
   def normalize(value):
    if isinstance(value,dict):return {k:normalize(v) for k,v in value.items() if k not in ['generatedAt']}
    if isinstance(value,list):return [normalize(v) for v in value]
    return value
   generated.append({f:normalize(json.loads((tree/f).read_text())) for f in ['repository.json','graph.json']})
   generated[-1]['schema']=json.loads(schema)
   generated[-1]['stats']={str(f.relative_to(tree)):json.loads(f.read_text()).get('stats') for f in sorted(tree.rglob('manifest.json'))}
  assert generated[0]==generated[1],'Generation differs'
 result={'cliRevision':pin,'contents':len(contents),'packages':len(manifests),'failures':failures,'generationReproducible':True,'normalization':'generatedAt timestamp only','artifactSha256':hashlib.sha256(json.dumps(generated[0],sort_keys=True).encode()).hexdigest()}
 (root/'docs/targeting-audit/validation.json').write_text(json.dumps(result,indent=2)+'\n')
 print(json.dumps(result));print('Detailed log:',logpath)
 if failures:sys.exit(1)
