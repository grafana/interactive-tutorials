#!/usr/bin/env python3
"""Run the catalog through pinned upstream code; do not emulate matching/ranking.
Usage: python3 scripts/targeting-audit/run.py --recommender /path/to/grafana-recommender
"""
import argparse, copy, hashlib, io, json, pathlib, subprocess, tarfile, tempfile
ROOT=pathlib.Path(__file__).resolve().parents[2]
BASE='ae282c99d260664c78b1fb703e678fe5098c814f'
ENGINE='b9adce44e8474441223c80d22ffcc92e6d465a55'
OUT=ROOT/'docs/targeting-audit'
def git(*args,cwd=ROOT): return subprocess.check_output(['git',*args],cwd=cwd)
def members(manifests):
    result={}
    for m in manifests:
        for child in m.get('milestones',[])+[g for track in m.get('tracks',[]) for g in track.get('guides',[])]:
            result.setdefault(child,[]).append(m['id'])
    return result

def rules(ms):
    return [dict(packageId=m['id'],repository='interactive-tutorials',title=m['id'],type='package',source='package',manifestType=m['type'],match=m['targeting']['match'],**{k:m[k] for k in ['startingLocation','depends','recommends','suggests'] if k in m}) for m in ms if m.get('targeting',{}).get('match')]
def walk(value):
    if isinstance(value,dict):
        yield value
        for v in value.values():yield from walk(v)
    elif isinstance(value,list):
        for v in value:yield from walk(v)

def write_candidate_review(inventory):
    from collections import defaultdict
    areas=defaultdict(list)
    for item in inventory:
        if item['disposition']!='path-module':areas[item['category'] or 'general'].append(item)
    lines=['# Candidate review by product area','','Generated by `scripts/targeting-audit/run.py` from the complete inventory. Source content, before/after rules, prerequisites and test contexts are in `inventory.json` and `scenarios.json`. Counts exclude path modules.','']
    for area,items in sorted(areas.items()):
        lines+=['## '+area,'','| Candidate | Learner task from content | Disposition / decision |','|---|---|---|']
        for x in items:
            task=(('; '.join(filter(None,x['sections']))) or ' '.join(x['taskEvidence']))[:220].replace('|','/').replace('\n',' ')
            lines.append(f"| [{x['id']}](../../{x['manifest']}) | {task} | {x['disposition']}: {x['decision']} |")
        lines.append('')
    (OUT/'candidates.md').write_text('\n'.join(lines).rstrip()+'\n')

def main():
    parser=argparse.ArgumentParser(__doc__);parser.add_argument('--recommender',required=True);args=parser.parse_args()
    files=git('ls-files','*manifest.json').decode().splitlines()
    before=[json.loads(git('show',f'{BASE}:{p}')) for p in files]
    after=[json.loads((ROOT/p).read_text()) for p in files]
    assert len({m['id'] for m in after})==len(after), 'Duplicate package identity'
    graph=members(after)
    assert set(graph) <= {m['id'] for m in after}, 'Unresolved path membership'
    # Foundations are the schema's milestones; tracks are additional membership edges.
    assert members([{'id':'a','milestones':['x'],'tracks':[{'guides':['y']}]},{'id':'b','milestones':['y']}])=={'x':['a'],'y':['a','b']}
    assert all(not m.get('targeting') for m in after if m['id'] in graph)
    scenarios=json.loads((OUT/'scenarios.json').read_text())
    candidates={m['id'] for m in after if m.get('targeting')}
    assert candidates <= {id for s in scenarios for id in s.get('include',[])}, 'Missing positive coverage'
    assert candidates <= {id for s in scenarios for id in s.get('exclude',[])}, 'Missing negative coverage'
    decisions=json.loads((OUT/'decisions.json').read_text())
    inventory=[]
    path_dirs={p.split('/')[0]:m['id'] for p,m in zip(files,after) if m['type']=='path'}
    for p,old,m in zip(files,before,after):
        cp=ROOT/p.replace('manifest.json','content.json');content=json.loads(cp.read_text());nodes=list(walk(content))
        containing=path_dirs.get(p.split('/')[0]) if len(p.split('/'))>2 else None
        module=m['id'] in graph or containing
        disposition='path-module' if module else ('recommendable' if m.get('targeting') else 'direct-only')
        assert not module or not m.get('targeting'),p
        prose=[n['content'] for n in nodes if isinstance(n.get('content'),str)]
        inventory.append(dict(id=m['id'],type=m['type'],manifest=p,content=str(cp.relative_to(ROOT)),contentSha256=hashlib.sha256(cp.read_bytes()).hexdigest(),disposition=disposition,parents=graph.get(m['id'],[]),containingPath=containing,category=m.get('category'),startingLocation=m.get('startingLocation'),taskEvidence=[' '.join(s.split())[:600] for s in prose[:2]],sections=[n.get('title') for n in nodes if n.get('type')=='section'],pageRequirements=sorted({s for n in nodes for s in n.get('requirements',[]) if isinstance(s,str) and s.startswith('on-page:')}),prerequisites={k:m[k] for k in ['depends','recommends','suggests','prerequisites'] if k in m},beforePrerequisites={k:old[k] for k in ['depends','recommends','suggests','prerequisites'] if k in old},before=old.get('targeting'),after=m.get('targeting'),decision=decisions.get(m['id'],'Path module/supporting lesson; retained for direct navigation and path execution, excluded from recommendations.' if module else 'Retain product/demo-specific rule: content task and route align; no unsupported task distinction introduced.')))
    (OUT/'inventory.json').write_text('[\n'+',\n'.join(json.dumps(x,ensure_ascii=False) for x in inventory)+'\n]\n')
    write_candidate_review(inventory)
    with tempfile.TemporaryDirectory(prefix='tutorial-targeting-engine-') as temp:
        temp=pathlib.Path(temp);archive=git('archive',ENGINE,cwd=args.recommender)
        with tarfile.open(fileobj=io.BytesIO(archive)) as tar:tar.extractall(temp,filter='data')
        (temp/'cmd/recommender/tutorial_catalog_audit_test.go').write_bytes((ROOT/'scripts/targeting-audit/server_test.go').read_bytes())
        inp=temp/'audit-input.json';inp.write_text(json.dumps(dict(before=rules(before),after=rules(after),scenarios=scenarios)))
        import os
        env=dict(os.environ,AUDIT_INPUT=str(inp),AUDIT_OUTPUT=str(temp/'results.json'))
        subprocess.run(['go','test','./cmd/recommender','-run','^TestTutorialCatalogAudit$|^TestV1Relevance_|^TestV1Ranking_','-count=1'],cwd=temp,env=env,check=True)
        subprocess.run(['go','test','./internal/recommender','-count=1'],cwd=temp,check=True)
        results=json.loads((temp/'results.json').read_text())
    # Compact raw responses but retain order, tier, accuracy and the evidence metadata.
    compact={phase:{name:{cap:[dict(id=r.get('manifest',{}).get('id',r.get('url')),relevance=r.get('relevance'),accuracy=r.get('matchAccuracy',0)) for r in recs] for cap,recs in caps.items()} for name,caps in scenario.items()} for phase,scenario in results.items()}
    (OUT/'results.json').write_text('{\n'+',\n'.join(json.dumps(phase)+': {\n'+',\n'.join(json.dumps(name)+': '+json.dumps(value) for name,value in cases.items())+'\n}' for phase,cases in compact.items())+'\n}\n')
    print(f'{len(inventory)} packages; {len(candidates)} recommendation candidates; {len(scenarios)} scenarios passed at caps 3, 10 and 10000')
if __name__=='__main__':main()
